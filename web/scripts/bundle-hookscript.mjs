// Bundles the Hookscript toolchain (../hookscript: compiler, reference interpreter, offline drafter, fuzzer and honeypot
// check) into one browser ES module, src/vendor/hookscript.js. The sources stay untouched: their few Node-only imports
// (fs, path, url, child_process, the Rust parity runner, the optional Anthropic SDK) are swapped for browser shims
// that are never reached on the offline path. The output is committed, so building the site doesn't need ../hookscript.
//   npm run hookscript          (re-run after any change in ../hookscript; npm test fails while the bundle is stale)
import { build } from 'esbuild';
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const WEB = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const HS = resolve(WEB, '../hookscript');
const OUT = join(WEB, 'src/vendor/hookscript.js');

/** Hash of every source file the bundle is made from (checked by tests/hookscript.test.mjs). */
export function sourceHash() {
  const h = createHash('sha256');
  const walk = (d) => {
    for (const f of readdirSync(d, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))) {
      const p = join(d, f.name);
      if (f.isDirectory()) walk(p);
      else if (/\.(ts|hs)$/.test(f.name)) { h.update(p.slice(HS.length)); h.update(readFileSync(p)); }
    }
  };
  for (const d of ['compiler/src', 'drafter', 'fuzz', 'examples']) walk(join(HS, d));
  return h.digest('hex').slice(0, 16);
}

const examples = Object.fromEntries(readdirSync(join(HS, 'examples')).filter((f) => f.endsWith('.hs')).sort().map((f) => [f.replace(/\.hs$/, ''), readFileSync(join(HS, 'examples', f), 'utf8')]));

const shims = {
  'node:fs': 'export const existsSync = () => false; export const readFileSync = () => { throw new Error("no fs in the browser"); }; export const readdirSync = () => []; export const writeFileSync = () => {}; export default {};',
  'node:path': 'export const join = (...p) => p.join("/"); export const dirname = (p) => String(p).replace(/\\/[^/]*$/, ""); export const basename = (p) => String(p).split("/").pop(); export default {};',
  'node:url': 'export const fileURLToPath = (u) => String(u).replace(/^file:\\/\\//, ""); export default {};',
  'node:child_process': 'export const spawnSync = () => ({ status: 1, stdout: "", stderr: "" }); export default {};',
  parity: 'export const runLine = () => ""; export const rustRun = () => []; export const tsLine = () => "";',
  anthropic: 'export default null;',
};

const entry = `
export { compile, disasm, run, verify, analyze, formatReason, ctx, wallet, decodeBase58, encodeBase58 } from ${JSON.stringify(join(HS, 'compiler/src/index.ts'))};
export { draft } from ${JSON.stringify(join(HS, 'drafter/draft.ts'))};
export { heuristicDraft } from ${JSON.stringify(join(HS, 'drafter/heuristic.ts'))};
export { fuzz } from ${JSON.stringify(join(HS, 'fuzz/fuzz.ts'))};
export { World, attempt, UNIT, SUPPLY, CREATOR_KEY, POOL_KEY } from ${JSON.stringify(join(HS, 'fuzz/world.ts'))};
export const EXAMPLES = ${JSON.stringify(examples)};
export const SOURCE_HASH = ${JSON.stringify(sourceHash())};
`;

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const r = await build({
    stdin: { contents: entry, resolveDir: HS, loader: 'js', sourcefile: 'hookscript-entry.js' },
    bundle: true, format: 'esm', platform: 'browser', target: 'es2022', minify: true, legalComments: 'none', write: false,
    define: { 'process.env': '{}' },
    plugins: [{
      name: 'browser-shims',
      setup(b) {
        b.onResolve({ filter: /^node:(fs|path|url|child_process)$/ }, (a) => ({ path: a.path, namespace: 'shim' }));
        b.onResolve({ filter: /compiler\/test\/parity\.ts$/ }, () => ({ path: 'parity', namespace: 'shim' }));
        b.onResolve({ filter: /^@anthropic-ai\/sdk$/ }, () => ({ path: 'anthropic', namespace: 'shim' }));
        b.onLoad({ filter: /.*/, namespace: 'shim' }, (a) => ({ contents: shims[a.path], loader: 'js' }));
      },
    }],
  });
  const banner = `// GENERATED by web/scripts/bundle-hookscript.mjs from ../hookscript (source hash ${sourceHash()}). Don't edit; run \`npm run hookscript\`.\n`;
  writeFileSync(OUT, banner + r.outputFiles[0].text);
  console.log(`wrote ${OUT.slice(WEB.length + 1)} (${(r.outputFiles[0].text.length / 1024).toFixed(0)} KB, ${Object.keys(examples).length} examples, hash ${sourceHash()})`);
}
